"""Crawl the fake site with the real crawl plan, build the snapshot, and
compare it with the committed fixture the Rust tests load.

Regenerate the fixture after an intentional change with:

    UPDATE_FIXTURES=1 uv run python -m unittest tests.test_end_to_end
"""

import json
import os
import unittest
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from fantasy_scraper.build import build_snapshot, validate_snapshot
from fantasy_scraper.cli import build_parser
from fantasy_scraper.scrape import ScrapeError, ScrapeOptions, SessionExpired, run_scrape

from . import fake_site as fs

NOW = datetime(2026, 10, 29, 21, 0, tzinfo=ZoneInfo("America/Los_Angeles"))
FIXTURE = Path(__file__).resolve().parents[2] / "fixtures" / "scraper_sample_snapshot.json"


def scrape(site=None, **opts):
    site = site or fs.FakeYahoo()
    result = run_scrape(site.fetch, ScrapeOptions(now=NOW, **opts), log=lambda _m: None)
    return build_snapshot(result, NOW, "Cripples and Bastards"), site


class EndToEndTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.snap, cls.site = scrape()

    def test_valid(self):
        self.assertEqual(validate_snapshot(self.snap), [])

    def test_counts(self):
        s = self.snap
        self.assertEqual(len(s["teams"]), 12)
        self.assertEqual(len(s["players"]), fs.N_PLAYERS)
        self.assertEqual(len(s["rosters"]), 24)          # 12 teams x weeks 1-2
        self.assertEqual(len(s["matchups"]), 12)         # 6 per week
        self.assertEqual(s["league"]["current_week"], 2)
        self.assertEqual(s["league"]["my_team_key"], "nba.l.106518.t.1")

    def test_season_totals_come_from_players_pages(self):
        for p in self.snap["players"]:
            exp = fs.season(int(p["player_key"].split(".")[-1]))
            for k, v in exp.items():
                self.assertAlmostEqual(p["season"][k], v, msg=f"{p['player_key']} {k}")

    def test_rosters_per_week(self):
        ro = {(r["week"], r["team_key"]): r["player_keys"] for r in self.snap["rosters"]}
        mine = "nba.l.106518.t.1"
        self.assertIn("nba.p.9012", ro[(1, mine)])
        self.assertNotIn("nba.p.9160", ro[(1, mine)])
        self.assertIn("nba.p.9160", ro[(2, mine)])
        self.assertNotIn("nba.p.9012", ro[(2, mine)])

    def test_weekly_stats(self):
        w = {(x["week"], x["player_key"]): x["stats"] for x in self.snap["weekly_stats"]}
        self.assertEqual(w[(1, "nba.p.9012")]["pts"], fs.weekly(9012, 1)["pts"])
        self.assertEqual(w[(2, "nba.p.9160")]["reb"], fs.weekly(9160, 2)["reb"])

    def test_transactions(self):
        tx = [(t["week"], t["team_key"].split(".")[-1], t["kind"], t["player_key"]) for t in self.snap["transactions"]]
        self.assertEqual(tx, [(1, "2", "drop", "nba.p.9025"), (1, "5", "add", "nba.p.9161"),
                              (1, "5", "drop", "nba.p.9055"), (2, "1", "add", "nba.p.9160"),
                              (2, "1", "drop", "nba.p.9012"), (2, "7", "add", "nba.p.9165")])
        self.assertTrue(any("trade" in w for w in self.snap["_yahoo"]["warnings"]))

    def test_polite_sequential_page_count(self):
        # 3 league pages + 12 teams + 2 scoreboards + 12 matchups + 2 tx + 9 player pages
        self.assertEqual(len(self.site.requests), 40)

    def test_gp_derived_when_no_gp_column(self):
        snap, site = scrape(fs.FakeYahoo(include_gp=False))
        self.assertEqual(validate_snapshot(snap), [])
        p = {x["player_key"]: x for x in snap["players"]}
        self.assertEqual(p["nba.p.9170"]["season"]["gp"], fs.season(9170)["gp"])
        self.assertTrue(any(lbl.endswith("_avg") for lbl in site.requests))

    def test_session_expiry_propagates(self):
        site = fs.FakeYahoo()

        def fetch(url, label):
            if label == "team_03":
                raise SessionExpired("redirected to login.yahoo.com")
            return site.fetch(url, label)

        with self.assertRaises(SessionExpired):
            run_scrape(fetch, ScrapeOptions(now=NOW), log=lambda _m: None)

    def test_logged_out_league_page(self):
        with self.assertRaises(ScrapeError):
            run_scrape(lambda u, l: "<html><body>Sign in</body></html>", ScrapeOptions(now=NOW),
                       log=lambda _m: None)

    def test_cli_parser(self):
        a = build_parser().parse_args(["snapshot", "--debug-dump", "--stats-weeks", "all", "--browser", "chromium"])
        self.assertTrue(a.debug_dump)
        self.assertEqual((a.stats_weeks, a.browser, a.league_id), ("all", "chromium", "106518"))

    def test_matches_committed_fixture(self):
        snap = dict(self.snap, _comment="SYNTHETIC fixture: generated by scraper/tests/test_end_to_end.py "
                    "from the fake pages in scraper/tests/fake_site.py. Not real Yahoo data.")
        text = json.dumps(snap, indent=1) + "\n"
        if os.environ.get("UPDATE_FIXTURES"):
            FIXTURE.write_text(text, encoding="utf-8")
        self.assertTrue(FIXTURE.exists(), f"{FIXTURE} missing; run with UPDATE_FIXTURES=1")
        self.assertEqual(json.loads(FIXTURE.read_text(encoding="utf-8")), json.loads(text),
                         "fixture out of date; rerun with UPDATE_FIXTURES=1 if the change is intended")


if __name__ == "__main__":
    unittest.main()
